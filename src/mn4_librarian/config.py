"""mn4-librarian의 기계적 상수(경로·분류체계와 무관한 값들).

경로(라이브러리 루트, 인박스, 로그 위치)는 사용자마다 다르므로 settings.py가 담당한다.
분류체계(대분류/소분류)도 사용자마다 다르므로 taxonomy.py가 라이브러리 폴더 구조에서
실시간으로 읽어온다. 이 파일에는 어느 사용자에게나 동일하게 적용되는 상수만 둔다.
"""
from __future__ import annotations

import os

# ---------------------------------------------------------------------------
# 파일명 규칙
# ---------------------------------------------------------------------------

# 표시할 저자 수 상한. 초과 시 "{저자1},{저자2} 외" 형식으로 축약한다.
MAX_AUTHORS_SHOWN = 2
AUTHOR_OVERFLOW_SUFFIX = " 외"

# 파일명에 쓸 수 없는/피해야 하는 문자와 대체 규칙.
# macOS Finder는 콜론을 막지만 스크립트·다운로드 도구가 만든 파일에는 남을 수 있다.
FILENAME_SANITIZE_MAP = {
    ":": "",
    "/": "-",
    "\\": "-",
}

# PDF가 아닌 파일, 숨김 파일 등 스캔에서 제외
IGNORED_FILENAME_PREFIXES = (".",)

# ---------------------------------------------------------------------------
# LLM 연동 (claude CLI, Max 구독 크레딧 사용 — API 키 미사용)
# ---------------------------------------------------------------------------

CLAUDE_BIN = os.environ.get("MN4_CLAUDE_BIN", "claude")
CLAUDE_MODEL = "sonnet"
CLAUDE_TIMEOUT_SEC = 90

# PDF에서 LLM에 넘길 텍스트 신호를 추출할 페이지 수 / 최대 문자 수
SIGNAL_PAGE_COUNT = 4
SIGNAL_MAX_CHARS = 4000
